// Пропускает дальше только запросы с активной сессией (после успешного /login).
// Если сессии нет — отвечает 401, а не тихо возвращает пустые данные:
// фронтенд по этому статусу поймёт, что нужно отправить пользователя на логин.
export function requireAuth(req, res, next) {
  if (!req.session.user) {
    res.status(401).json({ message: 'Требуется авторизация' });
    return;
  }
  next();
}
